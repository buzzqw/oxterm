//! Micro-benchmarks for the display-free core.
//!
//! Run with:
//!     cargo run --release --example bench-core
//!     cargo run --release --example bench-core -- --check
//!
//! This is deliberately dependency-free: it prints nanoseconds per operation
//! and, with `--check`, compares them against `bench/core-baseline.txt` so CI
//! can catch an accidental algorithmic regression (for example a setting lookup
//! turning into a linear scan per keystroke). Absolute timings vary between
//! machines, so the check uses a generous tolerance; it is a guard rail, not a
//! precise performance test.

use std::hint::black_box;
use std::time::Instant;

use oxterm::headless::{cli, framing, settings, spec, vi};

const BASELINE: &str = "bench/core-baseline.txt";

fn main() {
    let check = std::env::args().skip(1).any(|arg| arg == "--check");
    let write_baseline = std::env::args()
        .skip(1)
        .any(|arg| arg == "--write-baseline");
    let tolerance: f64 = std::env::var("BENCH_TOLERANCE")
        .ok()
        .and_then(|value| value.parse().ok())
        .unwrap_or(5.0);

    let argv: Vec<String> = ["--no-restore", "-o", "font_size=14", "--list-themes"]
        .iter()
        .map(|value| value.to_string())
        .collect();
    let document = r##"{"font_size": 14, "opacity": 0.95, "osc133": true,
        "custom_palette": {"black": "#101010"}, "snippets": {"t": "make test"},
        "tab_title": "term", "terminal_columns": 100, "terminal_rows": 30,
        "scrollback_lines": 50000, "color_scheme": "Nord"}"##;
    let line = "let mut value = foo(bar, baz) + quux(1, 2, 3); ".repeat(10);

    let results = [
        (
            "cli_parse_ns",
            bench(20_000, || {
                black_box(cli::parse_cli(black_box(&argv)).unwrap());
                1
            }),
        ),
        ("usage_ns", bench(5_000, || black_box(spec::usage()).len())),
        (
            "defaults_ns",
            bench(20_000, || {
                black_box(spec::defaults()).as_object().unwrap().len()
            }),
        ),
        (
            "validate_all_ns",
            bench(20_000, || {
                let mut ok = 0;
                for setting in spec::SETTINGS {
                    if spec::validate(setting, &setting.default_value()).is_ok() {
                        ok += 1;
                    }
                }
                black_box(ok)
            }),
        ),
        (
            "settings_document_ns",
            bench(5_000, || {
                black_box(
                    settings::load_document(black_box(document))
                        .unwrap()
                        .settings,
                )
                .as_object()
                .unwrap()
                .len()
            }),
        ),
        (
            "vi_motion_ns",
            bench(50_000, || {
                let mut col = 0;
                for _ in 0..8 {
                    col = vi::next_word_start(black_box(&line), col, false).unwrap_or(0);
                }
                black_box(col)
            }),
        ),
        (
            "framing_roundtrip_ns",
            bench(20_000, || {
                let mut buffer = Vec::with_capacity(256);
                framing::write_json(
                    &mut buffer,
                    black_box(&serde_json::json!({"op": "capture", "pane": "12345-1"})),
                    4096,
                )
                .unwrap();
                black_box(framing::read_json(&mut buffer.as_slice(), 4096).unwrap())
                    .as_object()
                    .unwrap()
                    .len()
            }),
        ),
    ];

    for (name, value) in &results {
        println!("{name}={value:.0}");
    }

    if write_baseline {
        let mut contents = String::from(
            "# Generated by `cargo run --release --example bench-core -- --write-baseline`.\n\
             # Values are nanoseconds per operation; CI allows BENCH_TOLERANCE (default 5x).\n",
        );
        for (name, value) in &results {
            contents.push_str(&format!("{name}={value:.0}\n"));
        }
        if let Some(parent) = std::path::Path::new(BASELINE).parent() {
            std::fs::create_dir_all(parent).expect("create bench directory");
        }
        std::fs::write(BASELINE, contents).expect("write baseline");
        eprintln!("wrote {BASELINE}");
    }

    if check {
        let baseline = std::fs::read_to_string(BASELINE).unwrap_or_default();
        let mut failed = false;
        for (name, value) in &results {
            let Some(expected) = baseline
                .lines()
                .filter(|line| !line.starts_with('#'))
                .find_map(|line| line.strip_prefix(&format!("{name}=")))
                .and_then(|value| value.trim().parse::<f64>().ok())
            else {
                eprintln!("skip {name}: no baseline");
                continue;
            };
            let limit = expected * tolerance;
            if *value > limit {
                eprintln!(
                    "regression {name}: {value:.0} ns/op > {limit:.0} ns/op (baseline {expected:.0}, tolerance {tolerance}x)"
                );
                failed = true;
            } else {
                println!(
                    "ok {name}: {value:.0} ns/op <= {limit:.0} ns/op (baseline {expected:.0})"
                );
            }
        }
        if failed {
            std::process::exit(1);
        }
    }
}

fn bench(iterations: u32, mut work: impl FnMut() -> usize) -> f64 {
    let iterations = iterations.max(1);
    // Warm up so the first allocation does not dominate a short run.
    for _ in 0..iterations / 10 + 1 {
        black_box(work());
    }
    let start = Instant::now();
    let mut total = 0usize;
    for _ in 0..iterations {
        total = total.wrapping_add(work());
    }
    let elapsed = start.elapsed().as_nanos() as f64;
    black_box(total);
    elapsed / f64::from(iterations)
}
