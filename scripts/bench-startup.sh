#!/usr/bin/env bash
#
# bench-startup.sh - measure Oxterm's startup and tab-creation cost.
#
# Usage:
#   ./scripts/bench-startup.sh                  # print measurements
#   ./scripts/bench-startup.sh --write-baseline # store them in bench/startup-baseline.txt
#   ./scripts/bench-startup.sh --check          # fail on a large regression
#
# The headless commands run without a display. The GUI part needs DISPLAY or
# WAYLAND_DISPLAY (CI runs the script under xvfb-run); when neither is set it is
# skipped and only the headless numbers are reported.
#
# Environment:
#   OXTERM_BIN        binary to measure (default: target/release/oxterm)
#   BENCH_RUNS        repetitions for the headless benchmarks (default: 5)
#   BENCH_GUI_ATTEMPTS launches used for the GUI startup figure (default: 3)
#   BENCH_TOLERANCE   allowed multiplier over the baseline (default: 4)

set -euo pipefail

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
BIN="${OXTERM_BIN:-${ROOT_DIR}/target/release/oxterm}"
BASELINE="${BENCH_BASELINE:-${ROOT_DIR}/bench/startup-baseline.txt}"
RUNS="${BENCH_RUNS:-5}"
GUI_ATTEMPTS="${BENCH_GUI_ATTEMPTS:-3}"
TOLERANCE="${BENCH_TOLERANCE:-4}"
MODE="${1:-run}"

if [[ ! -x "${BIN}" ]]; then
    printf '%s\n' "bench-startup: ${BIN} is missing; run 'cargo build --release' first" >&2
    exit 1
fi

# Keep the temporary HOME short: the control socket lives under it and Unix
# socket paths are limited to 107 bytes (Oxterm otherwise falls back to /tmp).
TMP_DIR="$(mktemp -d "${TMPDIR:-/tmp}/oxb.XXXXXX")"
APP_PID=""

cleanup() {
    if [[ -n "${APP_PID}" ]]; then
        kill "${APP_PID}" 2>/dev/null || true
        wait "${APP_PID}" 2>/dev/null || true
    fi
    rm -rf "${TMP_DIR}"
}
trap cleanup EXIT

now_ns() {
    date +%s%N
}

min_ms() {
    local best="" start end value
    for _ in $(seq "${RUNS}"); do
        start="$(now_ns)"
        "$@" >/dev/null 2>&1 || true
        end="$(now_ns)"
        value=$(( (end - start) / 1000000 ))
        if [[ -z "${best}" || "${value}" -lt "${best}" ]]; then
            best="${value}"
        fi
    done
    printf '%s' "${best}"
}

rss_kb() {
    awk '/VmRSS/{print $2}' "/proc/$1/status" 2>/dev/null || printf '0'
}

# Wait until the window is usable, not merely until it has a socket: `--list`
# only reports a session once the first tab and its shell exist.
wait_for_ready() {
    local home="$1" deadline=$((SECONDS + 20))
    while (( SECONDS < deadline )); do
        if HOME="${home}" "${BIN}" --list 2>/dev/null \
            | awk 'NR > 1 && NF { found = 1 } END { exit !found }'; then
            return 0
        fi
        sleep 0.02
    done
    return 1
}

measure_gui() {
    local home start end attempt ready
    GUI_READY_MS=""
    # Startup is measured several times and the best run is kept: the first
    # launch pays for cold caches and a loaded CI runner can stretch any single
    # one, while a real regression slows every attempt.
    for attempt in $(seq "${GUI_ATTEMPTS}"); do
        home="$(mktemp -d "${TMP_DIR}/h.XXXX")"
        start="$(now_ns)"
        HOME="${home}" "${BIN}" --no-restore >/dev/null 2>&1 &
        APP_PID=$!
        if ! wait_for_ready "${home}"; then
            printf '%s\n' "bench-startup: the GUI did not become ready" >&2
            return 1
        fi
        end="$(now_ns)"
        ready=$(( (end - start) / 1000000 ))
        if [[ -z "${GUI_READY_MS}" || "${ready}" -lt "${GUI_READY_MS}" ]]; then
            GUI_READY_MS="${ready}"
        fi
        GUI_RSS_KB="$(rss_kb "${APP_PID}")"

        # Tab creation is measured once, on the last (warm) launch.
        if (( attempt == GUI_ATTEMPTS )); then
            start="$(now_ns)"
            for index in $(seq 5); do
                HOME="${home}" "${BIN}" new --title "bench-${index}" >/dev/null 2>&1
            done
            end="$(now_ns)"
            TABS_MS=$(( (end - start) / 1000000 ))
            TABS_RSS_KB="$(rss_kb "${APP_PID}")"
        fi

        kill "${APP_PID}" 2>/dev/null || true
        wait "${APP_PID}" 2>/dev/null || true
        APP_PID=""
    done
}

VERSION_MS="$(min_ms "${BIN}" --version)"
SETTINGS_MS="$(min_ms "${BIN}" --list-settings)"
THEMES_MS="$(min_ms "${BIN}" --list-themes)"

GUI_READY_MS=""
GUI_RSS_KB=""
TABS_MS=""
TABS_RSS_KB=""
if [[ -n "${DISPLAY:-}${WAYLAND_DISPLAY:-}" ]]; then
    measure_gui || true
else
    printf '%s\n' "bench-startup: no display; skipping the GUI measurements" >&2
fi

RESULTS=(
    "version_ms=${VERSION_MS}"
    "settings_ms=${SETTINGS_MS}"
    "themes_ms=${THEMES_MS}"
    "gui_ready_ms=${GUI_READY_MS}"
    "gui_rss_kb=${GUI_RSS_KB}"
    "tabs_ms=${TABS_MS}"
    "tabs_rss_kb=${TABS_RSS_KB}"
)

for line in "${RESULTS[@]}"; do
    [[ "${line}" == *= ]] || printf '%s\n' "${line}"
done

baseline_value() {
    [[ -f "${BASELINE}" ]] || return 0
    awk -F= -v key="$1" '$1 == key { print $2; exit }' "${BASELINE}"
}

case "${MODE}" in
    --write-baseline)
        {
            printf '# Generated by scripts/bench-startup.sh --write-baseline.\n'
            printf '# Times are milliseconds (minimum of %s runs); RSS is KiB.\n' "${RUNS}"
            for line in "${RESULTS[@]}"; do
                [[ "${line}" == *= ]] || printf '%s\n' "${line}"
            done
        } >"${BASELINE}"
        printf '%s\n' "bench-startup: wrote ${BASELINE}" >&2
        ;;
    --check)
        failed=0
        for line in "${RESULTS[@]}"; do
            key="${line%%=*}"
            measured="${line#*=}"
            base="$(baseline_value "${key}")"
            if [[ -z "${base}" || -z "${measured}" ]]; then
                printf 'skip %s (no baseline or not measured)\n' "${key}"
                continue
            fi
            if [[ "${key}" == *rss* ]]; then
                # Memory varies with the allocator and the desktop; allow a
                # generous absolute margin.
                limit=$(( base * 3 + 65536 ))
            else
                limit=$(( base * TOLERANCE + 50 ))
            fi
            if (( measured > limit )); then
                printf 'REGRESSION %s: %s > %s (baseline %s)\n' \
                    "${key}" "${measured}" "${limit}" "${base}"
                failed=1
            else
                printf 'ok %s: %s <= %s (baseline %s)\n' \
                    "${key}" "${measured}" "${limit}" "${base}"
            fi
        done
        exit "${failed}"
        ;;
    run) ;;
    *)
        printf '%s\n' "bench-startup: unknown option: ${MODE}" >&2
        exit 2
        ;;
esac
